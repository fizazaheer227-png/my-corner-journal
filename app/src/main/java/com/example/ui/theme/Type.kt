fun getHandwritingFontFamily(styleName: String): FontFamily {
    return when (styleName.lowercase()) {
        "cursive" -> FontFamily.Cursive
        "script" -> FontFamily.Cursive
        "typewriter" -> FontFamily.Monospace
        "vintage serif" -> FontFamily.Serif
        else -> FontFamily.Default
    }
}

